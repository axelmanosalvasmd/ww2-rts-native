// Embed only the pinned reference's public map projection. Never copy raw map files into the server.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const REFERENCE_PIN = 'e4e579a838aabae3b1d9dadbc17a0a87147bc52d';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export async function loadReference(reference) {
  const pin = execFileSync('git', ['-C', reference, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim();
  assert.equal(pin, REFERENCE_PIN, 'map generation requires the pinned reference commit');
  assert.equal(execFileSync('git', ['-C', reference, 'status', '--porcelain'], {encoding:'utf8'}).trim(), '', 'map generation requires a clean reference');
  const { mapForClient } = await import(pathToFileURL(resolve(reference, 'shared/world-layers.js')));
  return mapForClient;
}

export async function assets(reference) {
  const project = await loadReference(reference);
  const filenames = (await readdir(resolve(reference, 'maps'))).filter(f => /^[a-z0-9-]{1,32}\.json$/.test(f)).sort();
  const result = new Map();
  const catalog = {};
  const names=[];
  for(const filename of filenames) {
    const name=filename.slice(0,-5);
    const raw=JSON.parse(await readFile(resolve(reference,'maps',filename),'utf8'));
    const safe=project(raw);
    assert.equal(safe.scenario,undefined);assert.equal(safe.triggers,undefined);
    assert.ok(safe.rows.every(row=>!row.includes('N')));
    assert.ok(safe.layers.objects.every(row=>!row.includes('N')));
    assert.ok(safe.layers.mines.every(row=>/^\.*$/.test(row)));
    result.set(`rust/crates/server/src/maps/${filename}`,JSON.stringify(safe)+'\n');
    names.push(name);
    catalog[name]={normal:raw.spawns.filter(s=>!s.assault).length,assault:raw.spawns.length,horde:!!raw.defend?.length};
  }
  // Sorting by the map name, rather than the filename, matches listMaps after stripping .json.
  names.sort();
  result.set('rust/crates/server/src/map-catalog.json',JSON.stringify(catalog,null,2)+'\n');
  result.set('rust/crates/server/src/map-data.rs',
    `// Generated by harness/map-assets.mjs from ww2-rts ${REFERENCE_PIN}.\n// These files contain only mapForClient projections, never raw authoring data.\n`+
    `#[rustfmt::skip]\npub(super) const MAPS: &[(&str, &str)] = &[\n`+
    names.map(name=>`    ("${name}", include_str!("maps/${name}.json")),`).join('\n')+'\n];\n');
  return result;
}

async function main() {
  const reference=resolve(process.env.WW2_REFERENCE || resolve(root,'reference/ww2-rts'));
  const check=process.argv.includes('--check');
  assert.ok(process.argv.slice(2).every(arg=>arg==='--check'),'only --check is supported');
  const generated=await assets(reference);
  const directory=resolve(root,'rust/crates/server/src/maps');
  if (!check) await mkdir(directory,{recursive:true});
  for(const [path,content] of generated) {
    if(check) assert.equal(await readFile(resolve(root,path),'utf8'),content,`${path} needs regeneration`);
    else await writeFile(resolve(root,path),content);
  }
  assert.deepEqual((await readdir(directory)).sort(),[...generated.keys()].filter(p=>p.includes('/maps/')).map(p=>p.split('/').at(-1)).sort(),'unexpected embedded maps');
  console.log(`${check?'Verified':'Generated'} ${generated.size-2} public map assets at reference ${REFERENCE_PIN.slice(0,7)}`);
}
if (process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) await main();
