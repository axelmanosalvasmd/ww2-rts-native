// Generate the server's private authoring assets separately from HTTP projections.
import assert from 'node:assert/strict';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadReference, REFERENCE_PIN } from './map-assets.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const reference = resolve(process.env.WW2_REFERENCE || resolve(root, 'reference/ww2-rts'));
await loadReference(reference);
const check = process.argv.includes('--check');
assert.ok(process.argv.slice(2).every(arg => arg === '--check'), 'only --check is supported');
const filenames = (await readdir(resolve(reference, 'maps')))
  .filter(name => /^[a-z0-9-]{1,32}\.json$/.test(name)).sort();
const directory = resolve(root, 'rust/crates/server/src/authoritative-maps');
if (!check) await mkdir(directory, { recursive: true });
let bytes = 0;
for (const name of filenames) {
  const original = JSON.parse(await readFile(resolve(reference, 'maps', name), 'utf8'));
  const content = JSON.stringify(original) + '\n';
  bytes += Buffer.byteLength(content);
  const target = resolve(directory, name);
  if (check) assert.equal(await readFile(target, 'utf8'), content, `${name} needs regeneration`);
  else await writeFile(target, content);
}
assert.deepEqual((await readdir(directory)).sort(), filenames, 'unexpected private map assets');
const names = filenames.map(name => name.slice(0, -5)).sort();
const index = `// Generated by harness/server-authored-maps.mjs from ww2-rts ${REFERENCE_PIN}.
// Original authoring data for native matches. HTTP handlers use the separate public index.
#[rustfmt::skip]
pub(super) const MAPS: &[(&str, &str)] = &[
${names.map(name => `    ("${name}", include_str!("authoritative-maps/${name}.json")),`).join('\n')}
];
`;
const target = resolve(root, 'rust/crates/server/src/authoritative-map-data.rs');
if (check) assert.equal(await readFile(target, 'utf8'), index, 'private map index needs regeneration');
else await writeFile(target, index);
console.log(`${check ? 'Verified' : 'Generated'} ${names.length} private authored maps, ${bytes} bytes, reference ${REFERENCE_PIN.slice(0, 7)}`);
