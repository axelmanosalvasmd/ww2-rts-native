// The ground's material tiles, made by the pinned reference itself: serves tiles.html with the read-only reference's
// client/ and shared/ and three from the pin's package-lock, opens it in headless Chromium (a throwaway profile) and
// saves what the page posts: tile-<material>-<T>.rgba (T x T RGBA, client/ground.js buildTiles output: the texture
// tiled 3 x 3, shrunk with the canvas's high-quality smoothing, the middle kept, tinted by LOOK mul, saturation and
// contrast), tiles.json (sizes, offsets, Chromium version) and, with --cases, the browser's textured canvas of oracle
// cases (<case>.<k>.browser.rgba) for the side by side.
//
// With --inl, the tiles are also written as C++ (the game's copy: Source/ThreeCrossroads/World/TCGroundPaint.Tiles.inl,
// RGB bytes, alpha is 255 throughout), so the native painter uses exactly these bytes with no texture readback.
//
//   node unreal/Tools/terrain/make-ground-tiles.mjs --three <dir with node_modules/three> --out <dir>
//        [--inl <path>] [--oracle <ground-oracle --out dir> --cases default,crater-field] [--chromium /usr/bin/chromium]
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { spawn, execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../..');
const reference = path.join(repo, 'reference/ww2-rts');
const arg = (name, d) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : d; };
const three = arg('three'), out = arg('out'), oracle = arg('oracle', ''), cases = arg('cases', ''), inl = arg('inl', '');
const chromium = arg('chromium', '/usr/bin/chromium'), timeout = +arg('timeout', 900);
if (!three || !out) { console.error('usage: make-ground-tiles.mjs --three <deps dir> --out <dir>'); process.exit(2); }
const pin = execFileSync('git', ['-C', reference, 'rev-parse', 'HEAD']).toString().trim();
if (execFileSync('git', ['-C', reference, 'status', '--porcelain']).toString().trim()) { console.error('reference/ww2-rts has local changes; refusing'); process.exit(1); }
fs.mkdirSync(out, { recursive: true });
const roots = { '/client/': path.join(reference, 'client'), '/shared/': path.join(reference, 'shared'), '/vendor/': path.join(three, 'node_modules/three/build'), '/terrain/': here, ...(oracle ? { '/oracle/': oracle } : {}) };
const types = { '.js': 'text/javascript', '.mjs': 'text/javascript', '.html': 'text/html', '.json': 'application/json', '.jpg': 'image/jpeg', '.webp': 'image/webp' };
const log = [];
let finish, saved = 0;
const done = new Promise((r) => (finish = r));
const server = http.createServer((req, res) => {
  const url = new URL(req.url, 'http://x');
  if (req.method === 'POST') {
    const chunks = [];
    req.on('data', (c) => chunks.push(c));
    req.on('end', () => {
      const body = Buffer.concat(chunks);
      if (url.pathname === '/save') { fs.writeFileSync(path.join(out, path.basename(url.searchParams.get('name'))), body); saved++; }
      else if (url.pathname === '/log') { log.push(body.toString()); console.log('page:', body.toString()); }
      else if (url.pathname === '/done') finish(body.toString());
      res.end('ok');
    });
    return;
  }
  const root = Object.keys(roots).find((r) => url.pathname.startsWith(r));
  const file = root && path.join(roots[root], decodeURIComponent(url.pathname.slice(root.length)));
  if (!file || !file.startsWith(roots[root]) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.statusCode = 404; res.end(); console.log('404', url.pathname); return; }
  res.setHeader('content-type', types[path.extname(file)] ?? 'application/octet-stream');
  fs.createReadStream(file).pipe(res);
});
// the tiles as C++: one byte array per tile (RGB), and a table the painter looks them up in
function writeInl(meta) {
  const L = ['// Generated by unreal/Tools/terrain/make-ground-tiles.mjs: do not edit. The pinned reference\'s client/ground.js buildTiles',
    `// output for every material and tile size the game can pick, made by ${meta.chromium} from client/textures at ${meta.reference}.`,
    '// RGB, row by row (alpha is 255 throughout). Read by World/TCGroundPaint.cpp and the standalone harness.', '#pragma once', '', 'namespace TCGroundPaintTiles', '{'];
  const list = [...meta.tiles].sort((a, b) => a.m - b.m || a.T - b.T);
  for (const t of list) {
    const raw = fs.readFileSync(path.join(out, `tile-${t.name}-${t.T}.rgba`));
    const rgb = [];
    for (let i = 0; i < raw.length; i += 4) { if (raw[i + 3] !== 255) throw new Error(`tile ${t.name}-${t.T} is not opaque`); rgb.push(raw[i], raw[i + 1], raw[i + 2]); }
    L.push(`\tinline const unsigned char Tile_${t.name}_${t.T}[${rgb.length}] = {`);
    for (let i = 0; i < rgb.length; i += 48) L.push('\t\t' + rgb.slice(i, i + 48).join(',') + ',');
    L.push('\t};');
  }
  L.push('\tstruct FEntry { const char* Name; int Material; int Size; const unsigned char* Rgb; };');
  L.push('\tinline const FEntry Entries[] = {');
  for (const t of list) L.push(`\t\t{ "${t.name}", ${t.m}, ${t.T}, Tile_${t.name}_${t.T} },`);
  L.push('\t};');
  L.push(`\tinline constexpr int Count = ${list.length};`);
  L.push(`\tinline constexpr const char* MadeBy = "${meta.chromium}, three ${meta.three}, reference ${meta.reference}";`);
  L.push('}', '');
  fs.writeFileSync(inl, L.join('\n'));
  console.log('wrote', inl, list.length, 'tiles');
}

server.listen(0, '127.0.0.1', () => {
  const port = server.address().port;
  const page = `http://127.0.0.1:${port}/terrain/tiles.html${cases ? `?cases=${cases}` : ''}`;
  const profile = path.join(out, '.chromium-profile');
  const browser = spawn(chromium, ['--headless=new', `--user-data-dir=${profile}`, '--no-first-run', '--no-default-browser-check', '--disable-extensions', '--disable-background-networking',
    '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--window-size=800,600', page], { stdio: ['ignore', 'ignore', 'pipe'] });
  browser.stderr.on('data', () => {});
  const timer = setTimeout(() => finish('timeout'), timeout * 1000);
  const exited = new Promise((r) => browser.on('exit', r));
  done.then(async (result) => {
    clearTimeout(timer);
    browser.kill('SIGTERM');
    server.close();
    await Promise.race([exited, new Promise((r) => setTimeout(r, 10000))]); // Chromium writes its profile while it exits
    fs.rmSync(profile, { recursive: true, force: true, maxRetries: 10, retryDelay: 300 });
    const meta = fs.existsSync(path.join(out, 'tiles.json')) ? JSON.parse(fs.readFileSync(path.join(out, 'tiles.json'), 'utf8')) : {};
    Object.assign(meta, { reference: pin, three: JSON.parse(fs.readFileSync(path.join(three, 'node_modules/three/package.json'), 'utf8')).version,
      chromium: execFileSync(chromium, ['--version']).toString().trim(), result, saved, log });
    fs.writeFileSync(path.join(out, 'tiles.json'), JSON.stringify(meta, null, 1));
    if (inl && result === 'ok') writeInl(meta);
    console.log('result', result, 'saved', saved);
    process.exit(result === 'ok' ? 0 : 1);
  });
});
