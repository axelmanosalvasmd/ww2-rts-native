// Trims a recorded Tutorial stream (player.mjs: every message the server sent one seat, one per line) to what the
// Client/TCTutorial recorded test replays: the lobbies, the start, and every snapshot that changed mode (step or goal),
// carried a 'say' shot, or first carried a winner. Unit rows, gone and held are dropped (the replay checks the guidance,
// not the rows; a snapshot without held clears the rows, as a server older than the deltas would); the say shots,
// mode, points, winner, end and out are kept as the server sent them. Writes the generated block of TCTutorial.cpp.
//   node make-tutorial-fixture.mjs <stream.jsonl> <TCTutorial.cpp> [--write]
import { readFileSync, writeFileSync } from 'node:fs';
const [file, cpp, flag] = process.argv.slice(2);
const out = [];
let lastMode = null, won = false;
for (const line of readFileSync(file, 'utf8').split('\n')) {
  if (!line) continue;
  const m = JSON.parse(line);
  if (m.t === 'lobby' || m.t === 'start') { out.push(m); continue; }
  if (m.t !== 's') continue;
  const mode = JSON.stringify(m.mode ?? null), says = (m.shots ?? []).filter(s => s.k === 'say');
  const first = m.winner != null && !won;
  if (mode === lastMode && !says.length && !first) continue;
  lastMode = mode; if (m.winner != null) won = true;
  const keep = { t: 's', tick: m.tick, units: [], points: m.points, mode: m.mode, shots: says, out: m.out };
  if (m.winner != null) { keep.winner = m.winner; keep.end = m.end; }
  out.push(keep);
}
const chunk = (s) => { const parts = []; for (let i = 0; i < s.length; i += 6000) parts.push(s.slice(i, i + 6000)); return parts.map(p => `R"TC(${p})TC"`).join('\n\t\t'); };
const lines = ['// GENERATED by make-tutorial-fixture.mjs from a live Tutorial stream on an isolated reference server (e4e579a): do not edit by hand',
  'static const TCHAR* const TutorialStream[] = {'];
for (const m of out) lines.push(`\tTEXT(${chunk(JSON.stringify(m))}),`);
lines.push('};', '// END FIXTURE');
const block = lines.join('\n');
console.error(`${out.length} messages kept (${out.filter(m => m.t === 's').length} snapshots), ${block.length} characters`);
if (flag === '--write') {
  const src = readFileSync(cpp, 'utf8'), a = src.indexOf('// GENERATED by make-tutorial-fixture.mjs'), b = src.indexOf('// END FIXTURE');
  if (a < 0 || b < 0) { console.error('no fixture block'); process.exit(1); }
  writeFileSync(cpp, src.slice(0, a) + block + src.slice(b + '// END FIXTURE'.length));
  console.error(`wrote ${cpp}`);
} else console.log(block);
