// Writes the reference tutorial's script (shared/tutorial.js STEPS: goal, at, say, mp, spawn) into the generated block
// of unreal/Source/ThreeCrossroads/Client/TCTutorial.cpp, and checks that client/es.js has the Spanish for every goal
// and line (the client shows them through the reference dictionary, keyed by the English text).
//
//   node export-tutorial.mjs <reference dir> [<TCTutorial.cpp> --write]
//
// Without --write it prints the block. The done() checks are code, not data, and are not exported: the client never
// decides a step; it reads mode.step from the server's snapshot.
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const [ref, cpp, flag] = process.argv.slice(2);
if (!ref) { console.error('usage: node export-tutorial.mjs <reference dir> [<TCTutorial.cpp> --write]'); process.exit(2); }
const { STEPS } = await import(pathToFileURL(join(ref, 'shared/tutorial.js')));
const ES = (await import(pathToFileURL(join(ref, 'client/es.js')))).default;
let pin = 'unknown';
try { pin = execFileSync('git', ['-C', ref, 'rev-parse', '--short=7', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

// C++ string literal (UTF-16 TEXT); the script is ASCII at e4e579a, anything else is written as \u escapes
const lit = (s) => 'TEXT("' + [...s].map(c => c === '"' ? '\\"' : c === '\\' ? '\\\\' : c.charCodeAt(0) < 128 ? c : '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0')).join('') + '")';
const missing = [];
const lines = [];
lines.push(`// GENERATED by export-tutorial.mjs from shared/tutorial.js at ${pin}: do not edit by hand`);
lines.push(`const TCHAR* const TCTutorialData::ReferencePin = TEXT("${pin}");`);
lines.push('static TArray<FTCTutorialStep> MakeSteps()');
lines.push('{');
lines.push('\tTArray<FTCTutorialStep> Out;');
for (const s of STEPS) {
  lines.push('\t{');
  lines.push('\t\tFTCTutorialStep& S = Out.AddDefaulted_GetRef();');
  lines.push(`\t\tS.Goal = ${lit(s.goal)}; S.At = FIntPoint(${s.at[0]}, ${s.at[1]}); S.Mp = ${s.mp ?? 0};`);
  for (const line of s.say) lines.push(`\t\tS.Say.Add(${lit(line)});`);
  for (const [type, x, y, o = {}] of s.spawn ?? []) {
    const parts = [`${lit(type)}`, `FIntPoint(${x}, ${y})`, `${o.hp ?? 0}`, o.go ? `true, FIntPoint(${o.go[0]}, ${o.go[1]})` : 'false, FIntPoint(0, 0)', o.house ? `true, FIntPoint(${o.house[0]}, ${o.house[1]})` : 'false, FIntPoint(0, 0)'];
    lines.push(`\t\tS.Spawn.Add(FTCTutorialSpawn{ ${parts.join(', ')} });`);
  }
  lines.push('\t}');
  for (const text of [s.goal, ...s.say]) if (!(text in ES)) missing.push(text);
}
lines.push('\treturn Out;');
lines.push('}');
lines.push('// END GENERATED');
const block = lines.join('\n');
if (missing.length) console.error(`es.js lacks ${missing.length} tutorial text(s):\n  ${missing.join('\n  ')}`);
else console.error(`es.js has all ${STEPS.reduce((a, s) => a + 1 + s.say.length, 0)} tutorial texts (${STEPS.length} goals and their lines)`);
if (flag === '--write' && cpp) {
  const src = readFileSync(cpp, 'utf8');
  const a = src.indexOf('// GENERATED by export-tutorial.mjs'), b = src.indexOf('// END GENERATED');
  if (a < 0 || b < 0) { console.error(`${cpp} has no generated block`); process.exit(1); }
  const next = src.slice(0, a) + block + src.slice(b + '// END GENERATED'.length);
  if (next !== src) { writeFileSync(cpp, next); console.error(`wrote ${cpp}`); } else console.error(`${cpp} is current`);
} else console.log(block);
process.exit(missing.length ? 1 : 0);
