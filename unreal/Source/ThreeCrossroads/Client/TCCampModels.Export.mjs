// Rebuild TCCampModels.Data.inl directly from the read-only pinned builders.
// node TCCampModels.Export.mjs --deps <pin npm install> [--check]
import { registerHooks } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = resolve(import.meta.dirname, '../../../..');
const args = process.argv.slice(2), depIndex = args.indexOf('--deps');
if (depIndex < 0 || !args[depIndex + 1]) throw Error('pass --deps DIR containing the pinned reference npm dependencies');
const deps = resolve(args[depIndex + 1]);
process.env.WW2_MODEL_DEPS = deps;
const { resolveThree } = await import(pathToFileURL(join(root, 'unreal/Tools/models/three-resolve.mjs')));
registerHooks({ resolve: resolveThree });
const { installShims, settle } = await import(pathToFileURL(join(root, 'unreal/Tools/models/shims.mjs')));
installShims();
const ref = join(root, 'reference/ww2-rts');
const git = (...args) => execFileSync('git', ['-C', ref, ...args], { encoding: 'utf8' }).trim();
if (git('rev-parse', 'HEAD') !== 'e4e579a838aabae3b1d9dadbc17a0a87147bc52d') throw Error('wrong reference pin');
if (git('status', '--porcelain')) throw Error('reference has local changes');
const wantVersion = JSON.parse(readFileSync(join(ref, 'package-lock.json'))).packages['node_modules/three'].version;
if (JSON.parse(readFileSync(join(deps, 'node_modules/three/package.json'))).version !== wantVersion) throw Error('three dependency is not the pinned version');
const THREE = await import('three');
const S = await import(pathToFileURL(join(ref, 'client/structures.js')));
await settle();
const bags = S.sandbagRing(15.8), box = new THREE.BoxGeometry(0.8, 0.6, 0.8);
const f = x => Number(x).toPrecision(10);
let out = '// Generated by TCCampModels.Export.mjs from e4e579a. Do not edit.\n';
for (const [name, geo] of [['Bag', bags.geometry], ['Node', box]]) {
 const g = geo.index ? geo.toNonIndexed() : geo;
 out += `static const double ${name}Vertices[][8] = {\n`;
 for (let i=0; i<g.attributes.position.count; i++) {
  const p=g.attributes.position,n=g.attributes.normal,u=g.attributes.uv;
  // +Y up metres to Unreal +Z up cm. Swap Y/Z; the original index order is now Unreal front-facing.
  out += `{${[p.getX(i)*100,p.getZ(i)*100,p.getY(i)*100,n.getX(i),n.getZ(i),n.getY(i),u?.getX(i)??0,u?.getY(i)??0].map(f).join(',')}},\n`;
 }
 out += '};\n';
}
out += 'static const double CampBags[][13] = {\n';
for(let i=0;i<bags.count;i++) {
 const m=new THREE.Matrix4(),p=new THREE.Vector3(),q=new THREE.Quaternion(),s=new THREE.Vector3(),c=new THREE.Color();
 bags.getMatrixAt(i,m);m.decompose(p,q,s);bags.getColorAt(i,c);
 out += `{${[p.x*100,p.z*100,p.y*100,-q.x,-q.z,-q.y,q.w,s.x,s.z,s.y,c.r,c.g,c.b].map(f).join(',')}},\n`;
}
out += '};\n';
const path=join(import.meta.dirname,'TCCampModels.Data.inl');
if(args.includes('--check')) { if(readFileSync(path,'utf8')!==out) throw Error('generated camp data differs'); }
else writeFileSync(path,out);
console.log(JSON.stringify({bags:bags.count,bagVertices:bags.geometry.index?.count??bags.geometry.attributes.position.count,nodeVertices:36,check:args.includes('--check')}));
