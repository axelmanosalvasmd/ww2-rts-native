// Execute pinned moveModel with minimal scene nodes. No reference files are modified.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../..');
class Group {
  constructor() { this.position={x:0,y:0,z:0}; this.rotation={x:0,y:0,z:0}; this.children=[]; this.visible=true; }
  add(child) { this.children.push(child); }
}
const source = fs.readFileSync(path.join(root,'reference/ww2-rts/client/model-motion.js'),'utf8')
  .replace("import * as THREE from 'three';",'').replace('export function moveModel','function moveModel');
const ctx = vm.createContext({THREE:{Group}, Math, Number});
vm.runInContext(source+';globalThis.moveModel=moveModel;',ctx);
const k = 1-Math.exp(-.1*10), x = 30+4*k, z = 30+2*k, rot = .4*k;
const v = {id:2,type:'gunboat',root:new Group()};
v.root.position.x=30; v.root.position.z=30;
ctx.moveModel(v,0);
v.root.position.x=x; v.root.position.z=z; v.root.rotation.y=-rot;
ctx.moveModel(v,.1);
const result = {x,z,rot,aim:1.2+(.2*k*.6),heave:v.visualBody.position.y,pitch:v.visualBody.rotation.z,roll:v.visualBody.rotation.x};
const header = '// Generated by TCWorld30VehicleOracle.mjs from pinned model-motion.js.\n' +
  'namespace TCWorld30Oracle {\n' + Object.entries(result).map(([key,value])=>`inline constexpr double ${key} = ${value.toPrecision(17)};`).join('\n')+'\n}\n';
if(process.argv.includes('--check')) {
  if(fs.readFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)),'TCWorld30VehicleOracle.inl'),'utf8')!==header) process.exit(1);
} else fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)),'TCWorld30VehicleOracle.inl'),header);
console.log(JSON.stringify(result));
